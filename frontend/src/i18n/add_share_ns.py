"""一次性注入脚本：为全部 12 个语种新增 `share` 命名空间（分享落地页文案）。

背景
----
`SharePage.tsx` 此前的按钮文案是**硬编码中文**（"分享" / "下载封面卡" / "去做一首
自己的歌" …）。而分享落地页恰恰是**陌生访客的第一屏** —— 他们多半来自其它语言区，
看到中文会直接关掉，病毒飞轮在这里断掉。所以随「分享到其他平台」一起做 i18n。

口径
----
- 键序固定（以本文件的 _KEYS 为准），保证 12 个语种键序一致、便于 diff
- 平台名（WeChat/Weibo/QQ/X/Facebook/WhatsApp/Telegram/Reddit/LinkedIn/Pinterest）
  在非中文语种保留**拉丁原名**（品牌名不意译）；zh 用「微信/微博/QQ」。
  ⚠️ 因此 parity_check.py 会把这些键在非 en 语种里计为 untranslated —— 属**预期
  假阳性**，与 appName=Melovar 同理。
- `shareText` 保留 `{title}` / `{url}` 占位符，交给 useTranslation 的 {x} 替换
- 幂等：重复执行结果一致；已存在同名命名空间则整体按 _KEYS 重建（不追加垃圾键）

用法
----
    python frontend/src/i18n/add_share_ns.py          # 写入
    python frontend/src/i18n/add_share_ns.py --check  # 只校验不写入
"""
