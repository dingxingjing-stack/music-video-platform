def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="只校验不写入")
    args = ap.parse_args()

    problems: list[str] = []
    for lang, table in T.items():
        missing = [k for k in _KEYS if k not in table]
        extra = [k for k in table if k not in _KEYS]
        if missing:
            problems.append(f"{lang}: 缺键 {missing}")
        if extra:
            problems.append(f"{lang}: 多余键 {extra}")

    if problems:
        print("翻译表自身不自洽，已中止：")
        for p in problems:
            print("  -", p)
        return 1

    if args.check:
        print(f"翻译表自洽（{len(T)} 语种 × {len(_KEYS)} 键）。")
        for lang in T:
            data = json.loads((LOCALES / f"{lang}.json").read_text(encoding="utf-8"))
            ns = data.get("share")
            if not isinstance(ns, dict):
                print(f"  {lang}: 缺少 share 命名空间")
                return 1
            diff = [k for k in _KEYS if ns.get(k) != T[lang][k]]
            print(f"  {lang}: {'OK' if not diff else '不一致 ' + str(diff)}")
        return 0

    for lang, table in T.items():
        path = LOCALES / f"{lang}.json"
        raw = path.read_text(encoding="utf-8")
        data = json.loads(raw)
        # 按 _KEYS 重建（保证键序一致、且不残留旧键）
        data["share"] = {k: table[k] for k in _KEYS}
        out = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
        path.write_text(out, encoding="utf-8")
        print(f"  {lang}.json 已写入 share（{len(_KEYS)} 键，文件 {len(raw)} -> {len(out)} 字节）")

    print("完成。")
    return 0


if __name__ == "__main__":
    sys.exit(main())
